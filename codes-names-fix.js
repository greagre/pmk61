/* =========================================================
   pmk61 / codes-names-fix.js  (v1, 27.11.2026)

   СЛОЙ: ИМЕНА КОМАНД БЕЗ СТРЕЛКИ

   ЧТО БЫЛО СЛОМАНО

   В codes-panel.js функция normalizeName приводит латинские буквы
   к русским, «->» к «→», убирает пробелы и точки — но саму стрелку
   «→» оставляет. Поэтому:

     normalizeName('П→X2')  →  'п→х2'
     normalizeName('Пх 2')  →  'пх2'      ← не совпало

   Проверка 1 в codes-keys-test.html из-за этого красная. Хуже того,
   в самом калькуляторе разбор нажатий не узнавал запись «Пх2»:
   человек пишет так же часто, как «П→X2», а панель отвечала
   «не знаю команду».

   ЧТО ДЕЛАЕТ СЛОЙ

     1. Подменяет наружную MKCodePanel.normalizeName на версию,
        которая сначала выбрасывает стрелку, а потом нормализует.
     2. Дополняет внутреннюю таблицу «имя → код» вариантами БЕЗ
        стрелки, чтобы её видел и внутренний разбор parseKeys
        (он пользуется своей, замкнутой копией функции).

   Обратная таблица строится из MKCore.cmdName — один источник
   истины с листингом и подсказками. Кэш nameIndex() возвращает
   сам объект, поэтому дописывание ключей в него видно всем.

   ПОЧЕМУ СЛОЕМ, А НЕ ПРАВКОЙ codes-panel.js

   Тот же приём, что у vo-fix.js и nop-fix.js: файл панели 28 тысяч
   знаков, запись идёт целиком, и любая правка внутри рискует
   потерять соседний код. Одна строка подключения снимает слой
   без следа. Если панель когда-нибудь научится сама — слой просто
   удаляется.

   ГДЕ СТОИТ В index.html

   Сразу после codes-panel.js. Раньше нельзя: MKCodePanel ещё
   не создан. Позже можно, но тогда до подключения панель успела бы
   ответить на первое нажатие старым разбором.
   ========================================================= */
(function (global) {
  'use strict';

  var P = global.MKCodePanel;
  if (!P || typeof P.normalizeName !== 'function') return;
  if (P.__namesFix) return;              /* второй раз не оборачиваем */
  P.__namesFix = true;

  var oldNorm = P.normalizeName;

  /* Стрелка выбрасывается ДО нормализации: «П→X2» и «Пх2» дают
     один и тот же ключ. Порядок «П→X» и «X→П» при этом сохраняется:
     «пх2» и «хп2» — разные команды. */
  function norm(s) {
    return oldNorm(String(s == null ? '' : s).replace(/[\u2192\u21D2]/g, ''));
  }

  P.normalizeName = norm;

  /* Перестроить таблицу имён и добавить варианты без стрелки.
     Внутренний parseKeys пользуется прежней (замкнутой) функцией,
     поэтому ключи должны быть в таблице в обоих видах. */
  try {
    P.resetNames();
    var map = P.nameIndex();
    var MK = global.MKCore;
    if (MK && typeof MK.cmdName === 'function' && map) {
      for (var c = 0; c < 256; c++) {
        var nm = null;
        try { nm = MK.cmdName(c); } catch (e) { nm = null; }
        if (!nm) continue;
        var k = norm(nm);
        if (k && map[k] === undefined) map[k] = c;
      }
    }
  } catch (e) { /* таблица не построилась — панель продолжит работать как раньше */ }

  global.MKCodesNamesFix = { version: 1, normalizeName: norm };
})(typeof window !== 'undefined' ? window : this);
