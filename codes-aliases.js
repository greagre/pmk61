/* =========================================================
   pmk61 / codes-aliases.js  (v2, 27.11.2026)

   СЛОЙ: СИНОНИМЫ ИМЁН КОМАНД ИЗ ЧУЖИХ ЛИСТИНГОВ

   ЗАЧЕМ

   Одна и та же команда в разных книгах и эмуляторах пишется
   по-разному: «П→X2», «Пx2», «ПX2», «ИП2». Панель кодов узнавала
   только то, как команду печатает наше ядро (MKCore.cmdName),
   и на «ИП2», «X#0», «KB», «L2» отвечала «не знаю команду».

   Здесь собран словарь вариантов: каждая строка — группа
   синонимов одной и той же команды.

   ВАЖНО ПРО ИСТОЧНИК

   Таблица взята из файла мнемоник чужой программы (mMnemonics).
   Оттуда берётся ТОЛЬКО НАПИСАНИЕ. Нумерация кодов в том файле
   другая: там С/П = 3A, БП = 3D, В/О = 39, а у нас С/П = 50,
   БП = 51, В/О = 52. Если бы мы взяли оттуда индексы, программы
   молча поехали бы по чужим адресам.

   Поэтому код каждой группы определяется ЗДЕСЬ, по нашей таблице:
   берём любой вариант, приводим к ключу и ищем в nameIndex(),
   который построен из MKCore.cmdName. Не нашлось — группа
   пропускается целиком и попадает в отчёт skipped. Так в отчёт
   уходят недокументированные команды чужой машины (3C, 3D, 2B,
   4F…FF), которых у нас нет и не будет.

   ЧТО НОВОГО В v2

   Аргументные команды. «ИП2» — это одна команда с аргументом,
   а не имя «ИП» плюс отдельная цифра. В v1 в карту попадал только
   ключ «ип» (без цифры), поэтому слипшееся «ИП2» и раздельное
   «ИП 3» не узнавались, а в программе терялись сразу две команды.

   Теперь для каждой формы имени и каждой цифры 0…E строится
   отдельный ключ:

       ип2 → код «П→X2»      хп2 → код «X→П2»
       ип3 → код «П→X3»      пх3 → код «П→X3»

   Код берётся не арифметикой (+n), а из нашей же карты: эталон
   ищется по имени, которое печатает ядро («П→X2»). Так слой
   не зависит от того, как расположены коды в памяти.

   КАК ПОПАДАЕТ В РАЗБОР

   nameIndex() возвращает кэш-объект, а parseKeys() берёт его же.
   Поэтому достаточно дописать ключи в этот объект — внутренний
   разбор увидит их без правки самого файла панели.

   Ключей на каждый вариант пишется два:

     baseNorm(v)  — ровно так, как посчитает внутренний parseKeys
                     (он пользуется замкнутой копией normalizeName
                     и стрелку НЕ выбрасывает);
     normKey(v)   — после наших замен: ** -> ^, >= -> ≥, # -> ≠,
                     буква O вместо нуля, ^2 -> ², -1 -> ⁻¹.

   Первый нужен, чтобы совпасть с внутренним разбором, второй —
   чтобы понимать записи, которые базовой нормализации не поддаются.

   ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ

     • одиночная «П» как синоним X→П — она перехватывала бы начало
       «П→X2» и ломала самый частый случай;
     • одиночные «F» и «FF» — мусорные имена чужой таблицы;
     • группа «F↻» — у неё в синонимах стоит голая стрелка «→»,
       после нормализации она превращается в пустой ключ и могла бы
       совпасть с чем угодно.

   ГДЕ СТОИТ В index.html

   После codes-panel.js и codes-names-fix.js: панель должна уже
   существовать, а имена без стрелки — уже быть в таблице, иначе
   наши ключи получат коды по неполной карте.
   ========================================================= */
(function (global) {
  'use strict';

  var P = global.MKCodePanel;
  if (!P || typeof P.nameIndex !== 'function') return;
  if (P.__aliases) return;                 /* второй раз не строим */
  P.__aliases = true;

  /* ---------- группы синонимов (написание, не коды) ---------- */

  var GROUPS = [
    /* степень десяти */
    ['F10^x', '10ˣ', 'F10^X', '10X', 'F10X', '10**X'],
    /* К НОП */
    ['KНОП', 'НОП', 'K0'],
    /* e^x */
    ['F e^x', 'Eˣ', 'FE^X', 'E^X', 'EX', 'FEX', 'FE**X', 'E**X'],
    /* lg, ln */
    ['F lg', 'LG'],
    ['F ln', 'LN'],
    /* К Ч→М */
    ['KЧ→М', 'KЧM', 'ЧM', 'K3'],
    /* обратные тригонометрические */
    ['F sin⁻¹', 'SIN⁻¹', 'FSIN-1', 'FARCSIN', 'ARCSIN', 'SIN-1'],
    ['F cos⁻¹', 'COS⁻¹', 'FCOS-1', 'FARCCOS', 'ARCCOS', 'COS-1'],
    ['F tg⁻¹', 'TG⁻¹', 'FTG-1', 'FARCTG', 'ARCTG', 'TG-1'],
    /* К |x|, К зн */
    ['K|x|', '|X|', 'K4'],
    ['K зн', 'ЗН', 'K5'],
    /* К Г→М */
    ['KГ→М', 'Г→М', 'KГM', 'ГM', 'K6'],
    /* прямые тригонометрические */
    ['F sin', 'FSIN', 'SIN'],
    ['F cos', 'FCOS', 'COS'],
    ['F tg', 'FTG', 'TG'],
    /* К [x], К {x}, К max */
    ['K[x]', '[X]', 'K7'],
    ['K{x}', '{X}', '(X)', 'K(X)', 'K8'],
    ['K max', 'KMAX', 'MAX', 'K9'],
    /* знаки операций */
    ['−', '–'],
    ['×', '⋅', '*'],
    ['÷', '/', ':'],
    /* π */
    ['F π', 'FΠ', 'ПИ', 'Π', 'FПИ'],
    /* К М→Г */
    ['KМ→Г', 'M→Г', 'KMГ', 'MГ', 'K+'],
    /* корень */
    ['F √', '√', 'KBKOР', 'KOРEНЬ', 'KBKOРEНЬ', 'FKBKOР', 'FKOРEНЬ', 'FKBKOРEНЬ', 'КОРЕНЬ'],
    /* квадрат, обратное число */
    ['F x²', 'FX²', 'X^2', 'X2', 'X²', 'FX^2', 'FX2'],
    ['F 1/x', 'F1/X', '1/X'],
    /* обмен */
    ['↔', '<->', 'XY', 'X↔Y', '⟷'],
    /* В↑ */
    ['В↑', 'B↑', '^', 'B^', '↑'],
    /* степень */
    ['F xʸ', 'FXʸ', 'Xʸ', 'FX^Y', 'X^Y', 'FXY'],
    /* К− К× К÷ */
    ['K −', 'K–'],
    ['K ×', 'KX', 'K*'],
    ['K ÷', 'K/', 'K:'],
    /* К М→Ч */
    ['KМ→Ч', 'M→Ч', 'KM→Ч'],
    /* F Вх, К СЧ */
    ['F Вх', 'FBX', 'ВX'],
    ['K СЧ', 'KCЧ', 'CЧ', 'KE'],
    /* смена знака, ВП, Cx */
    ['/-/', '+/-'],
    ['ВП', 'BП'],
    ['Cx', 'CX'],
    /* логические */
    ['К ∧', 'KɅ', 'КɅ', 'K^', 'K⋀', 'K∧', '∧', '⋀', 'KA', 'KΛ', 'K.'],
    ['К ∨', 'KV', 'Kv', 'K⋁', 'K∨', '∨', '⋁', 'KB'],
    ['К ⊕', 'K(+)', 'K⊕', '(+)', '⊕', 'KBП', 'KC'],
    ['К ИНВ', 'Kинв', 'ИНB', 'KCX', 'KD'],
    /* служебные */
    ['В/О', 'B/0', 'B/O'],
    ['С/П', 'C/П'],
    /* сравнения с нулём */
    ['Fx≥0', 'X>=0', 'X≥0', 'X⩾0', 'Fx≥O', 'X>=O', 'X≥O', 'X⩾O'],
    ['Fx≠0', 'X#0', 'X!=0', 'X<>0', 'FX#0', 'FX!=0', 'FX<>0',
      'FX≠O', 'X#O', 'X!=O', 'X<>O', 'FX#O', 'FX!=O', 'FX<>O'],
    ['Fx<0', 'X<0', 'FX<O', 'X<O'],
    ['Fx=0', 'X=0', 'FX=O', 'X=O'],
    /* переходы */
    ['БП'],
    ['ПП'],
    ['F L0', 'L0', 'FLO', 'LO'],
    ['F L1', 'L1'],
    ['F L2', 'L2'],
    ['F L3', 'L3'],
    /* косвенные */
    ['X→П', 'XП', 'X→П'],
    ['П→X', 'Пx', 'ПX', 'П→X', 'ИП'],
    ['Kx≠0', 'KX≠0', 'KX#0', 'KX!=0', 'KX<>0',
      'KX≠O', 'KX#O', 'KX!=O', 'KX<>O'],
    ['Kx≥0', 'KX≥0', 'KX⩾0', 'KX>=0', 'Kx≥O', 'KX≥O', 'KX⩾O', 'KX>=O'],
    ['Kx<0', 'KX<0', 'KX<O'],
    ['Kx=0', 'KX=0', 'KX=O'],
    ['KБП'],
    ['KПП'],
    ['KxП', 'KXП', 'KX→П', 'KП', 'КП'],
    ['KПx', 'KПX', 'KП→x', 'KП→X', 'KИП']
  ];

  /* ---------- аргументные команды (v2) ---------- */

  /* Имя, после которого идёт цифра регистра/адреса.
     etalon — то, как эту команду печатает наше ядро; по нему ищем код
     в карте, поэтому арифметика «база + n» не нужна. */
  var ARG_SETS = [
    { etalon: 'П→X', forms: ['П→X', 'Пx', 'ПX', 'ИП'] },        /* 60…6E */
    { etalon: 'X→П', forms: ['X→П', 'XП', 'ХП'] },              /* 40…4E */
    { etalon: 'Kx≠0', forms: ['Kx≠0', 'KX≠0', 'KX#0', 'KX!=0',
                              'KX<>0', 'KX≠O', 'KX#O', 'KX!=O', 'KX<>O'] },
    { etalon: 'Kx≥0', forms: ['Kx≥0', 'KX≥0', 'KX⩾0', 'KX>=0'] },
    { etalon: 'Kx<0', forms: ['Kx<0', 'KX<0'] },
    { etalon: 'Kx=0', forms: ['Kx=0', 'KX=0'] },
    { etalon: 'F L', forms: ['F L', 'FL', 'L'] }
  ];

  var HEXDIG = '0123456789ABCDE'.split('');

  /* ---------- ключи ---------- */

  /* Копия normalizeName из codes-panel.js. Нужна точь-в-точь: внутренний
     parseKeys считает ключ своей замкнутой копией и стрелку не убирает. */
  var LIKELY = {
    p: 'п', x: 'х', c: 'с', b: 'в', k: 'к', a: 'а',
    e: 'е', o: 'о', t: 'т', m: 'м', h: 'н', y: 'у'
  };

  function baseNorm(s) {
    var t = String(s == null ? '' : s).toLowerCase();
    t = t.replace(/->|=>|—>|–>/g, '→');
    t = t.replace(/\*/g, '×');
    t = t.replace(/\//g, '÷');
    t = t.replace(/[−–—-]/g, '−');
    t = t.replace(/[pxcbkaeotmhy]/g, function (ch) { return LIKELY[ch] || ch; });
    t = t.replace(/\s+/g, '');
    t = t.replace(/\./g, '');
    return t;
  }

  /* Замены, которых нет в базовой нормализации: именно из-за них
     «10**X», «X>=0», «X#0» раньше не узнавались. */
  function pre(s) {
    var t = String(s == null ? '' : s);
    t = t.replace(/\*\*/g, '^');
    t = t.replace(/<->|⟷|↔|⇔/g, '\u2194');
    t = t.replace(/>=|⩾/g, '≥');
    t = t.replace(/<=|⩽/g, '≤');
    t = t.replace(/!=|<>|#/g, '≠');
    t = t.replace(/([≥≤≠=<>])[OoОо]/g, '$10');
    t = t.replace(/Π/g, 'π');
    t = t.replace(/\^2(?![0-9])/g, '²');
    t = t.replace(/\^3(?![0-9])/g, '³');
    t = t.replace(/ᐨ¹|⁻¹/g, '⁻¹');
    t = t.replace(/([a-zа-яё])[-−–]1(?![0-9])/g, '$1⁻¹');
    return t;
  }

  function normKey(s) {
    return baseNorm(pre(s));
  }

  function put(map, key, code, stats) {
    if (!key) return;
    if (map[key] === undefined) { map[key] = code; stats.added++; }
  }

  /* ---------- построение ---------- */

  var map = P.nameIndex();
  var stats = { groups: 0, added: 0, skipped: [], total: GROUPS.length, args: 0 };

  if (map) {
    for (var i = 0; i < GROUPS.length; i++) {
      var g = GROUPS[i];
      var code;
      var j, k1, k2;

      for (j = 0; j < g.length; j++) {
        k1 = baseNorm(g[j]);
        k2 = normKey(g[j]);
        if (k1 && map[k1] !== undefined) { code = map[k1]; break; }
        if (k2 && map[k2] !== undefined) { code = map[k2]; break; }
      }
      if (code === undefined) {
        stats.skipped.push(g[0]);
        continue;
      }
      stats.groups++;
      for (j = 0; j < g.length; j++) {
        k1 = baseNorm(g[j]);
        k2 = normKey(g[j]);
        put(map, k1, code, stats);
        if (k2 !== k1) put(map, k2, code, stats);
      }
    }

    /* v2: имя + цифра 0…E для аргументных команд */
    for (var s = 0; s < ARG_SETS.length; s++) {
      var set = ARG_SETS[s];
      for (var d = 0; d < HEXDIG.length; d++) {
        var dig = HEXDIG[d];
        var refCode = map[baseNorm(set.etalon + dig)];
        if (refCode === undefined) continue;
        for (var f = 0; f < set.forms.length; f++) {
          var key = baseNorm(set.forms[f] + dig);
          if (key && map[key] === undefined) {
            map[key] = refCode;
            stats.added++;
            stats.args++;
          }
        }
      }
    }
  }

  global.MKCodesAliases = {
    version: 2,
    normKey: normKey,
    baseNorm: baseNorm,
    groups: stats.groups,
    added: stats.added,
    args: stats.args,
    total: stats.total,
    skipped: stats.skipped,
    index: function () { return P.nameIndex(); }
  };
})(typeof window !== 'undefined' ? window : this);
