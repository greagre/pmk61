/* =========================================================
   pmk61 / x1-fix.js
   Ревизия: извлечение X1 (F Вx) с подъёмом стека.
   Ядро core.js не переписывается — правка отдельным слоем.

   Что говорит руководство
   -----------------------
   Стек: 4 регистра (X, Y, Z, T) плюс X1 — «дополнительный регистр,
   куда автоматически сохраняется прежнее значение X при выполнении
   команды, которая меняет содержимое X».

   Извлечение прежнего X (F Вx) по руководству вызывает автоматический
   подъём стека: X уходит в Y, Y в Z, Z в T, прежнее T теряется —
   освобождается место в X, куда кладётся значение из X1.

   core.js делает иначе
   --------------------
     if (code === 0x0F) { var t = ST.X1; ST.X1 = ST.X; ST.X = t; }
   то есть просто МЕНЯЕТ X и X1 местами. Подъёма нет: Y, Z, T
   остаются на месте, а в X1 попадает прежнее X.

   Как проверить расхождение
   -------------------------
     5 √ F Вx

   Было в эмуляторе:  X=5, Y=0, Z=0, T=0, X1=2.236…  (обмен)
   По руководству:    X=5, Y=2.236…, Z=0, T=0

   Второй опыт (7 √ F Вx) дал X=7, Y=0, X1=2.645… — подъёма нет.

   Как исправляется
   ----------------
   Слой ставится ПОСЛЕ core.js и оборачивает create(), как vo-fix.js:
     - core.step — свой шаг: перед настоящим шагом запоминаются X, Y, Z
       и X1; если исполнялась команда 0x0F, после шага стек ставится
       правильно — подъём плюс X1 в X;
     - core.run — свой прогон, чтобы обёрнутый шаг работал и там.

   Открытый вопрос
   ---------------
   Что происходит с самим X1 после извлечения, руководство прямо не
   оговаривает. Здесь принято, что X1 СОХРАНЯЕТ прежнее значение
   (команда повторяемая: повторное F Вx снова даст то же число).
   Проверяется опытом; если руководство скажет иначе — правится
   одна строка ниже.

   Зачем отдельным файлом
   ----------------------
   core.js синхронизируется с greagre/pmk52, правка внутри ядра должна
   попасть в оба репозитория сразу. Отдельный слой живёт в pmk61,
   снимается одной строкой из index.html.
   ========================================================= */
(function (global) {
  'use strict';

  var MK = global.MKCore;
  if (!MK || MK.__x1Fix) return;

  var FX = 0x0F;          /* F Вx — извлечение прежнего X */

  var origCreate = MK.create;

  /* Пригодится тестам: создать ядро без слоя и сравнить. */
  MK.__origCreate = MK.__origCreate || origCreate;

  MK.create = function (options) {
    var core = origCreate(options);
    var ST = core.ST;
    var origStep = core.step;

    function stepFixed() {
      var prevIp = ST.ip;
      var code = ST.prog[prevIp];
      var isFx = (code === FX);
      var xOld, yOld, zOld, x1Old;

      if (isFx) {
        xOld = ST.X;
        yOld = ST.Y;
        zOld = ST.Z;
        x1Old = ST.X1;
      }

      var res = origStep();

      /* Настоящий шаг уже сделал обмен X<->X1. Ставим стек по руководству:
         подъём X->Y, Y->Z, Z->T (T теряется), в X — значение из X1. */
      if (isFx) {
        ST.X = x1Old;
        ST.Y = xOld;
        ST.Z = yOld;
        ST.T = zOld;
        ST.X1 = x1Old;
      }
      return res;
    }

    core.step = stepFixed;

    /* Свой прогон: повторяет поведение core.run, но зовёт stepFixed. */
    core.run = function (limit) {
      var max = limit || 100000;
      var n = 0, res = 'cont';
      ST.err = false;
      ST.steps = 0;
      while (n < max) {
        res = stepFixed();
        n++;
        ST.steps = n;
        if (res === 'stop' || res === 'error') break;
      }
      return {
        result: res,
        steps: n,
        err: ST.err,
        x: ST.X,
        overflow: (n >= max && res !== 'stop' && res !== 'error')
      };
    };

    return core;
  };

  MK.__x1Fix = true;
  MK.X1_FIX = FX;
})(typeof window !== 'undefined' ? window : this);
